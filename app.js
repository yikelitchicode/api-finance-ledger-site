const fmt = (n) => {
  const num = Number(n || 0);
  return Number.isFinite(num) ? num.toLocaleString('zh-HK', { minimumFractionDigits: 2, maximumFractionDigits: 2 }) : '—';
};

const typeLabel = (row) => {
  const raw = row.display_type || row.type || '—';
  const map = { income: '收入', expense: '支出', refund: '退款', recharge: '充值', setup: '初始化' };
  return map[raw] || raw;
};

const sourceLabel = (row) => row.source_set === 'recharge_log' ? '充值記錄' : 'API 賬本';

function renderSummary() {
  document.getElementById('total-income').textContent = '¥ ' + fmt(summaryData.income);
  document.getElementById('total-expense').textContent = '¥ ' + fmt(summaryData.expense);
  document.getElementById('total-refund').textContent = '¥ ' + fmt(summaryData.refund);
  document.getElementById('total-net').textContent = '¥ ' + fmt(summaryData.net);

  const list = document.getElementById('currency-breakdown');
  const entries = Object.entries(currencyTotals);
  list.innerHTML = entries.length ? entries.map(([key, value]) => {
    const [typ, cur] = key.split('|');
    const cn = { income: '收入', expense: '支出', refund: '退款', setup: '初始化' }[typ] || typ;
    return `<li><span>${cn} · ${cur}</span><strong>${fmt(value)}</strong></li>`;
  }).join('') : '<li><span>暫無外幣統計</span><strong>—</strong></li>';
}

function renderRows(rows) {
  const tbody = document.getElementById('records-body');
  tbody.innerHTML = rows.map((row) => `
    <tr>
      <td>${row.date || '—'}</td>
      <td>${row.platform_or_source || '—'}</td>
      <td><span class="pill type-${row.type || 'other'}">${typeLabel(row)}</span></td>
      <td>${row.amount || '—'}</td>
      <td>${row.currency || '—'}</td>
      <td>${row.rmb_amount ? '¥ ' + fmt(row.rmb_amount) : '—'}</td>
      <td>${sourceLabel(row)}</td>
      <td>${row.note || '—'}</td>
    </tr>
  `).join('');

  document.getElementById('record-count').textContent = `${rows.length} 筆`;
}

function applyFilters() {
  const keyword = document.getElementById('search-input').value.trim().toLowerCase();
  const type = document.getElementById('type-filter').value;
  const source = document.getElementById('source-filter').value;

  const rows = ledgerData.filter((row) => {
    const hay = [row.date, row.platform_or_source, row.note, row.currency, row.source_set, row.display_type]
      .join(' ')
      .toLowerCase();
    if (keyword && !hay.includes(keyword)) return false;
    if (type && row.type !== type && row.display_type !== type) return false;
    if (source && row.source_set !== source) return false;
    return true;
  });

  renderRows(rows);
}

renderSummary();
renderRows(ledgerData);
['search-input', 'type-filter', 'source-filter'].forEach((id) => {
  document.getElementById(id).addEventListener('input', applyFilters);
  document.getElementById(id).addEventListener('change', applyFilters);
});
